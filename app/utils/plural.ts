/**
 * Русское склонение числительных: plural(5, 'предмет', 'предмета', 'предметов').
 *
 * Правило одинаковое везде, а функция была продублирована в трёх файлах, и
 * на этом споткнулась новая вкладка «Содержимое»: многоточие в шаблоне без
 * объявления даёт «plural is not a function» в консоли и пустой экран.
 * Одно место — одна правка.
 *
 * Считает по последним двум цифрам: «11» — это many, а не one, хотя
 * последняя цифра единица. Отсюда и проверка mod100, а не только mod10.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10
  const mod100 = n % 100

  if (mod10 === 1 && mod100 !== 11) return one
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few

  return many
}
