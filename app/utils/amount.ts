/**
 * Число для показа в интерфейсе.
 *
 * Остатки по свойствам бывают дробными (0,3 л), и в базе они лежат числами.
 * Простое приведение к строке давало бы «0.30000000000000004» и «1800.0» — то
 * есть либо хвост из-за округления, либо лишний ноль у целого.
 *
 * Разряды не группируются пробелами: в таблице такая запись («1 800 мл») занимает
 * вдвое больше ширины, чем «1800 мл», а колонка «Количество» и без того узкая.
 */
export function formatAmount(value: number | null | undefined): string {
  if (value === null || value === undefined || Number.isNaN(Number(value))) {
    return '0'
  }

  const rounded = Math.round(Number(value) * 1000) / 1000

  return String(rounded)
}
