/**
 * Запас, разложенный по штукам: сколько целых норм помещается и сколько
 * остаётся сверху.
 *
 * Считается делением с остатком, а не через `ceil(total / norm)` с допуском
 * вида «почти целое считаем за целое». Разница видна на больших числах:
 * 40 001 мл при норме 10 000 — это четыре полные штуки и один миллилитр в
 * пятой, то есть пять штук; округление перед делением теряло либо штуку,
 * либо миллилитр, и результат зависел от величины.
 *
 * Остаток возвращается как есть — человек должен видеть не «4 шт», а
 * «4 шт и 1 мл сверху», потому что именно эта единица объясняет, почему
 * штук пять.
 */
export type StockSplit = {
  /** Сколько целых штук помещается в запас. */
  whole: number
  /** Сколько остаётся сверх целых штук, в единицах измерения. */
  remainder: number
  /** Итоговое число штук: целые плюс одна неполная, если остаток есть. */
  pieces: number
}

export function splitByNorm(total: number, norm: number): StockSplit {
  if (!(norm > 0) || !(total > 0)) {
    return { whole: 0, remainder: 0, pieces: 0 }
  }

  const whole = Math.floor(total / norm)
  // Остаток через вычитание, а не `%`: при дробных нормах деление с остатком
  // в JS не определено, а вычитание даёт тот же самый остаток.
  const remainder = total - whole * norm

  return {
    whole,
    remainder: remainder > 0 ? remainder : 0,
    pieces: remainder > 0 ? whole + 1 : whole,
  }
}

/**
 * Запас в штуках по норме.
 *
 * Отдельной функцией, а не свойством `pieces`, потому что в подсказке нужно
 * одно, а в проверке — другое, и путать их дорого.
 */
export function piecesInStock(total: number, norm: number): number {
  return splitByNorm(total, norm).pieces
}
