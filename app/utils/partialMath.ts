/**
 * Деление с округлением «в штуки»: сколько целых частей помещается в запас.
 *
 * Кажется, что достаточно `Math.ceil(total / norm)`, но не хватает: 2000.0000001
 * мл при норме 1000 мл — это три штуки (две полные и одна с каплей), а без
 * допуска получилось бы две. Допуск ровно тот, что на сервере: расхождение на
 * единицу штуки в подсказке выглядит как ошибка системы, даже если система
 * права.
 *
 * Допуск абсолютный и маленький — 1e-6. Больше брать нельзя: при крупных числах
 * (40 001 мл при норме 10 000) вычитание 1e-4 превращало 4.0001 ровно в 4, и
 * подсказка показывала четыре штуки вместо пяти.
 */
export const PART_TOLERANCE = 1e-6

/** Сколько штук помещается в запас: `Math.ceil(total / norm)` с допуском. */
export function piecesInStock(total: number, norm: number): number {
  if (!(norm > 0) || !(total > 0)) {
    return 0
  }

  return Math.ceil(total / norm - PART_TOLERANCE)
}
