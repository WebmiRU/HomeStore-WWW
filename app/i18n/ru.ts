/** Ключ в плоском виде: 'nav.items', 'items.form.title'. */
export type TranslationKey = Flatten<typeof ru>

/** Раскрывает вложенный словарь в плоские точечные ключи. */
type Flatten<T> = T extends string
  ? ''
  : {
      [K in keyof T & string]: T[K] extends string ? K : `${K}.${Flatten<T[K]>}`
    }[keyof T & string]
