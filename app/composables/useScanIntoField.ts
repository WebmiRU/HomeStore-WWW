/**
 * Сканер, прицеленный в поле кода, должен наполнить это поле, а не увести
 * страницу на главную.
 *
 * Глобальный обработчик в app.vue события из редактируемых элементов
 * отбрасывает — иначе он ловил бы и обычный набор текста. Побочный эффект
 * был в том, что при фокусе в поле кода отсканированное не попадало никуда:
 * буфер сканера копился вхолостую, а поле оставалось прежним.
 *
 * ## Правило одно: во время набора поле не трогаем
 *
 * Все версии по очереди вставляли символы в поле по мере прихода, и все
 * показывали одну и ту же мерзость: сканер целится в поле, где уже есть
 * код, — и новый дописывается к старому, а потом старый исчезает. Где именно
 * ломалось, неважно: вставка на лету означает, что в поле какое-то время
 * лежит мусор, который надо ещё и успеть убрать.
 *
 * Поэтому символы копятся в буфере, а поле пишется один раз, в конце. Поле
 * со старым кодом на всей протяжении скана — это, кстати, то самое, на что
 * и нужно целяться сканером.
 *
 * ## Почему первый символ тоже уходит в буфер
 *
 * Отдельная оптимизация была: первый символ набора отдавать браузеру, чтобы
 * ручной ввод не ждал debounce. Так и поступило приложение, и сканер
 * писал в конец старого кода ровно одну первую цифру — она успевала
 * появиться и исчезала. Значит первый символ отдавать нельзя: набрать его
 * «по-быстрому» нельзя, а сканер отличить от человека — можно, но не
 * мгновенно.
 *
 * ## Чем скан отличается от ручного ввода
 *
 * Только временем между клавишами: сканер даёт символы подряд, человек
 * печатает медленнее. Порог тот же, что и debounce глобального обработчика
 * в app.vue, — проверенное на этих же сканерах число.
 *
 * И важно, что порог один, а не два. Сперва казалось, что нужны два: один,
 * чтобы «это один набор» (иначе код рвётся посреди скана и в поле попадает
 * только хвост), и второй, чтобы «это скан». С двумя порогами набор рвался
 * по первому, и вместо мусора на экране получалась потеря части кода — что
 * хуже мусора. С одним порогом набор не рвётся, а различение идёт по
 * длине: длинный набор — скан, короткий — ручной ввод.
 *
 * ## Ручной ввод
 *
 * Символы попадают в буфер, но буфер короткий, и через 100мс тишины он
 * вписывается обратно — на место, где стоял курсор. Задержка меньше интервала
 * между клавишами у человека, поэтому набор выглядит обычным набором, а
 * ничего не теряется.
 *
 * ## Перекодировка в латиницу
 *
 * Сканер — клавиатурный клин: он шлёт коды клавиш, и при русской раскладке
 * в поле уехали бы буквы-близнецы вместо латинских, то есть в код попал бы
 * мусор. Поэтому символ берётся через keyToLatin (по e.code, а не по e.key).
 */
import { keyToLatin } from '~/utils/scanKey'

/** Пауза короче этого — символ продолжает набор. */
const BURST_GAP_MS = 100
/** Столько ждём тишины, прежде вписать накопленное обратно. */
const SCAN_IDLE_MS = 100
/** Короче этого набор кодом не считается. */
const MIN_CODE_LEN = 8
/**
 * Сколько после записанного скана ещё гасить Enter.
 *
 * Сканер шлёт Enter суффиксом, но USB-сканеры делают это с разной задержкой,
 * а у дешёвых он иногда не настроен вовсе. Без этого окна Enter от такого
 * сканера отправил бы форму, то есть сохранил бы предмет, который человек
 * не закончил.
 */
const ENTER_AFTER_SCAN_MS = 700

export function useScanIntoField() {
  /** Символы текущего набора. */
  let pending = ''
  /** Поле набора и его содержимое с курсором на момент начала. */
  let target: HTMLInputElement | null = null
  let startPos = 0
  let endPos = 0
  let lastKeyAt = 0
  let idleTimer: ReturnType<typeof setTimeout> | null = null
  /** Когда в поле последний раз записан скан. */
  let scanWrittenAt = 0

  function clearIdle() {
    if (idleTimer) {
      clearTimeout(idleTimer)
      idleTimer = null
    }
  }

  function reset() {
    pending = ''
    target = null
    lastKeyAt = 0
    clearIdle()
  }

  /**
   * Вписывает накопленный набор в поле и забывает его.
   *
   * Длинный набор — это скан, и значение заменяется целиком: сканер не видит
   * прежнего содержимого, и дописывая, он склеил бы «СТАРЫЙ-КОД» с новым.
   * Короткий — это набранное руками, и оно возвращается между startPos и
   * endPos, то есть туда, где стоял курсор: иначе правка середины кода
   * сдвинула бы символы.
   */
  function flush() {
    const input = target
    const chars = pending

    reset()

    if (input === null || chars === '') {
      return
    }

    const scanned = chars.length >= MIN_CODE_LEN
    const value = scanned
      ? chars
      : input.value.slice(0, startPos) + chars + input.value.slice(endPos)
    const caret = scanned
      ? chars.length
      : startPos + chars.length

    if (value !== input.value) {
      setNativeValue(input, value)
      input.setSelectionRange(caret, caret)
      input.dispatchEvent(new Event('input', { bubbles: true }))
    }

    if (scanned) {
      scanWrittenAt = Date.now()
    }
  }

  /** Начинает набор в поле, запоминая, где стоял курсор. */
  function startBurst(input: HTMLInputElement) {
    target = input
    startPos = input.selectionStart ?? input.value.length
    endPos = input.selectionEnd ?? startPos
  }

  function onKeydown(e: KeyboardEvent) {
    // Служебные сочетания — не ввод: Ctrl+V, Alt+стрелки и прочее оставляем
    // браузеру, иначе вставка из буфера обмена перестала бы работать.
    if (e.ctrlKey || e.metaKey || e.altKey) {
      return
    }

    const input = e.target as HTMLInputElement | null

    // В поле, которое нельзя править, сканеру делать нечего: значение
    // подменилось бы незаметно, а сохранить его всё равно нельзя.
    if (input === null || input.readOnly || input.tagName !== 'INPUT') {
      return
    }

    if (e.key === 'Enter') {
      if (pending.length >= MIN_CODE_LEN) {
        // Скан ещё в буфере — Enter закрывает его, но форму не отправляет.
        e.preventDefault()
        e.stopPropagation()
        flush()
        return
      }

      if (Date.now() - scanWrittenAt < ENTER_AFTER_SCAN_MS) {
        // Скан уже записан, но Enter от него пришёл с задержкой.
        e.preventDefault()
        e.stopPropagation()
        flush()
        return
      }

      // Ручной ввод: набор дописывается на своё место, а Enter ведёт себя как
      // прежде, то есть сохраняет форму.
      if (pending !== '') {
        flush()
      }
      return
    }

    const char = keyToLatin(e)
    if (char === '') {
      return
    }

    const now = Date.now()

    if (now - lastKeyAt > BURST_GAP_MS) {
      // Настоящая пауза: то, что копилось, надо вписать, иначе потеряется.
      if (pending !== '') {
        flush()
      }

      startBurst(input)
    } else if (target !== input) {
      // Фокус перескочил на другое поле, а набор продолжился: прежнее
      // содержимое уже не актуально, запоминаем новое.
      flush()
      startBurst(input)
    }

    // Обычная вставка отменяется всегда, включая первый символ: иначе он
    // на секунду мелькнёт в поле и исчезнет при подмене значения.
    e.preventDefault()

    pending += char
    lastKeyAt = now

    clearIdle()
    idleTimer = setTimeout(flush, SCAN_IDLE_MS)
  }

  return { onKeydown }
}

/**
 * Значение через setter прототипа, а не через присваивание.
 *
 * Присваивание в обход Vue не проходит: поле не знает, что его значение
 * изменили, и на следующем обновлении компонента вернёт старое. Событие
 * input после setter'а нужно поэтому не «для галочки» — именно его слушает
 * v-model.
 */
function setNativeValue(input: HTMLInputElement, value: string) {
  const setter = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')?.set
  setter?.call(input, value)
}
